#!/usr/bin/env python3
"""Generate the two `#print axioms` audit files of the skeleton library and check their output.

    python3 make_axioms.py            # (re)write Axioms.lean and src/Skeleton/Top/Axioms.lean
    python3 make_axioms.py --check axioms.txt
                                       # verify an output file: every line must be
                                       # "does not depend on any axioms" or
                                       # "[propext, Classical.choice, Quot.sound]"; no sorryAx

Run from skeleton/ (one `lean` process at a time):

    python3 make_axioms.py
    export PATH=$HOME/.elan/bin:$PATH
    lake env lean Axioms.lean > axioms.txt                      # whole library (import Skeleton)
    lake env lean src/Skeleton/Top/Axioms.lean > src/Skeleton/Top/axioms.txt

`Axioms.lean` lists every public theorem/lemma of the library plus every public definition,
structure or abbrev whose (last) name starts with a capital letter -- by Lean's convention these
are the propositions (`Layer3`, `PlugWin`, `VWin`, `Green`, `EveryCharacter`, ...) and the
structures they are built from.  Private declarations are skipped (not addressable from outside).
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'src', 'Skeleton')
decl_re = re.compile(r'^(\s*)(?:@\[[^\]]*\]\s*)*(?:(private|protected|noncomputable|unsafe|partial|scoped)\s+)*'
                      r'(theorem|lemma|def|structure|abbrev|inductive)\s+([A-Za-z_\u0080-\uffff][\w.\'\u0080-\uffff!]*)', re.UNICODE)
ns_re = re.compile(r'^\s*(?:private\s+)?namespace\s+([A-Za-z0-9_.\u0080-\uffff]+)')
end_re = re.compile(r'^\s*(?:private\s+)?end\b\s*([A-Za-z0-9_.\u0080-\uffff]*)')
STANDARD = '[propext, Classical.choice, Quot.sound]'


def declarations(path):
    """(name, kind) of the public declarations of one Lean file, namespace-aware."""
    out, ns, depth = [], [], 0
    with open(path, encoding='utf-8') as fh:
        for line in fh:
            stripped = line.lstrip()
            if depth > 0:                                   # inside a block comment
                depth += stripped.count('/-') - stripped.count('-/')
                continue
            if stripped.startswith('--'):
                continue
            if stripped.startswith('/-'):
                depth += stripped.count('/-') - stripped.count('-/')
                continue
            m = ns_re.match(line)
            if m:
                ns.append(m.group(1)); continue
            m = end_re.match(line)
            if m and m.group(1):
                if ns and (ns[-1] == m.group(1) or ns[-1].split('.')[-1] == m.group(1).split('.')[-1]):
                    ns.pop()
                continue
            m = decl_re.match(line)
            if not m:
                continue
            mods, kind, name = m.group(2) or '', m.group(3), m.group(4)
            if 'private' in mods.split():
                continue
            if name.startswith('_root_'):
                name = name[len('_root_'):]
                full = name
            else:
                full = '.'.join(ns + [name])           # Lean 4: `theorem A.b` inside `namespace N` is `N.A.b`
            if kind in ('theorem', 'lemma') or name.rsplit('.', 1)[-1][0].isupper():
                out.append((full, kind))
    return out


def collect(subdir=None):
    names = {}
    root = SRC if subdir is None else os.path.join(SRC, subdir)
    for dp, dn, fn in os.walk(root):
        for f in sorted(fn):
            if not f.endswith('.lean') or f.startswith('Axioms'):
                continue
            for n, k in declarations(os.path.join(dp, f)):
                names[n] = k
    return names


def write_audit(path, names, header, imp):
    out = [f'/- {header} (generated by skeleton/make_axioms.py; do not edit). -/',
           f'import {imp}', '',
           'set_option pp.proofs.withType false in', '']
    thm = sorted(n for n, k in names.items() if k in ('theorem', 'lemma'))
    dfn = sorted(n for n, k in names.items() if k not in ('theorem', 'lemma'))
    out += ['-- propositions and structures'] + [f'#print axioms {n}' for n in dfn] + ['', '-- theorems and lemmas']
    out += [f'#print axioms {n}' for n in thm]
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(out) + '\n')


def check(path):
    """Every declaration line must list a subset of the three standard axioms (or none)."""
    allowed = {'propext', 'Classical.choice', 'Quot.sound'}
    counts, bad = {}, []
    with open(path, encoding='utf-8', errors='replace') as fh:
        for line in fh:
            s = line.strip()
            if not s or s.startswith('#') or s.startswith('(-'):      # header comments / Lake output
                continue
            if s.endswith('does not depend on any axioms'):
                counts['(none)'] = counts.get('(none)', 0) + 1
            elif ' depends on axioms: [' in s and s.endswith(']'):
                ax = [a.strip() for a in s.rsplit('[', 1)[1][:-1].split(',') if a.strip()]
                if set(ax) <= allowed:
                    counts['[' + ', '.join(ax) + ']'] = counts.get('[' + ', '.join(ax) + ']', 0) + 1
                else:
                    bad.append(line.rstrip())
            else:
                bad.append(line.rstrip())
    total = sum(counts.values())
    print(f'{path}: {total} declarations checked; ' + '; '.join(f'{v} × {k}' for k, v in sorted(counts.items(), key=lambda kv: -kv[1])))
    print(f'    non-standard axioms: {len(bad)}; sorryAx: {sum("sorryAx" in b for b in bad)}')
    for b in bad[:20]:
        print('   ', b)
    return 0 if not bad else 1


if __name__ == '__main__':
    if len(sys.argv) > 2 and sys.argv[1] == '--check':
        sys.exit(check(sys.argv[2]))
    allnames = collect()
    write_audit(os.path.join(HERE, 'Axioms.lean'), allnames,
                'Axiom audit of the whole skeleton library: `#print axioms` for every public theorem and for every '
                'proposition / structure.  Run `lake env lean Axioms.lean > axioms.txt` (output kept in axioms.txt).',
                'Skeleton')
    topnames = collect('Top')
    write_audit(os.path.join(HERE, 'src', 'Skeleton', 'Top', 'Axioms.lean'), topnames,
                'Axiom audit for every declaration of `Skeleton/Top` (run `lake env lean src/Skeleton/Top/Axioms.lean`; '
                'output in axioms.txt next to this file).  Not imported by anything.',
                'Skeleton.Top')
    n_thm = sum(1 for k in allnames.values() if k in ('theorem', 'lemma'))
    print(f'{len(allnames)} declarations ({n_thm} theorems/lemmas) -> Axioms.lean; '
          f'{len(topnames)} declarations -> src/Skeleton/Top/Axioms.lean', file=sys.stderr)
