#!/usr/bin/env python3
"""Generate skeleton/Axioms.lean: one `#print axioms` per public theorem/lemma of the
skeleton library (namespace-aware), so that `lake env lean Axioms.lean > axioms.txt` shows
which axioms every separately citable statement depends on.  Run from skeleton/:

    python3 make_axioms.py && PATH=$HOME/.elan/bin:$PATH lake env lean Axioms.lean > axioms.txt
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'src', 'Skeleton')
decl_re = re.compile(r'^(\s*)(?:@\[[^\]]*\]\s*)*(?:(private|protected|noncomputable|unsafe|partial)\s+)*'
                     r'(theorem|lemma)\s+([A-Za-z_][A-Za-z0-9_.\'!]*)')
ns_re = re.compile(r'^\s*(?:private\s+)?namespace\s+([A-Za-z0-9_.]+)')
end_re = re.compile(r'^\s*end\b\s*([A-Za-z0-9_.]*)')

names = []
for dp, dn, fn in os.walk(SRC):
    for f in sorted(fn):
        if not f.endswith('.lean'):
            continue
        ns = []
        depth = 0                      # inside a block comment (docstrings quote original statements!)
        with open(os.path.join(dp, f), encoding='utf-8') as fh:
            for line in fh:
                stripped = line.lstrip()
                if depth > 0:
                    depth += stripped.count('/-') - stripped.count('-/')
                    continue
                if stripped.startswith('--'):
                    continue
                if stripped.startswith('/-'):
                    depth += stripped.count('/-') - stripped.count('-/')
                    continue
                m = ns_re.match(line)
                if m:
                    ns.append(m.group(1)); continue
                m = end_re.match(line)
                if m and m.group(1):
                    if ns and (ns[-1] == m.group(1) or ns[-1].split('.')[-1] == m.group(1).split('.')[-1]):
                        ns.pop()
                    continue
                m = decl_re.match(line)
                if m:
                    if 'private' in (m.group(2) or ''):      # private declarations are not addressable from outside
                        continue
                    names.append('.'.join(ns + [m.group(4)]))
names = sorted(set(names))
out = ['/- Generated by make_axioms.py: `#print axioms` for every public theorem of the skeleton. -/',
       'import Skeleton', '',
       'set_option pp.proofs.withType false in', '']
for n in names:
    out.append(f'#print axioms {n}')
with open(os.path.join(HERE, 'Axioms.lean'), 'w') as fh:
    fh.write('\n'.join(out) + '\n')
print(f'{len(names)} theorems -> Axioms.lean', file=sys.stderr)
